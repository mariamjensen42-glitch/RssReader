/** Map a persisted locale setting (or null = follow system) to a supported dictionary. */
export function resolveLocale(setting: string | null | undefined): SupportedLocale {
    if (!setting || setting === "default") {
        if (typeof navigator !== "undefined" && navigator.language.toLowerCase().startsWith("zh")) return "zh"
        return "en"
    }
    return setting.toLowerCase().startsWith("zh") ? "zh" : "en"
}

/** Build a translate function for the resolved locale. Unknown keys fall back to English, then the key itself. */
export function makeT(locale: string | null | undefined): (key: string, params?: Record<string, string | number>) => string {
    const dict = resolveLocale(locale) === "zh" ? zh : en
    return (key, params) => {
        let s = dict[key] ?? en[key] ?? key
        if (params) {
            for (const [k, v] of Object.entries(params)) {
                s = s.replaceAll(`{${k}}`, String(v))
            }
        }
        return s
    }
}
